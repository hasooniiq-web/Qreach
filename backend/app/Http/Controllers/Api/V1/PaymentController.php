<?php

namespace App\Http\Controllers\Api\V1;

use App\Http\Controllers\Controller;
use App\Models\Payment;
use App\Models\SubscriptionPlan;
use App\Services\Payments\GatewayRegistry;
use App\Services\Payments\PaymentException;
use App\Services\Payments\PaymentService;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Str;

/**
 * The customer's side of paying for a plan. Starting a payment returns the
 * provider's checkout URL; the *result* is never taken from the app — the app
 * only polls show() while the server learns the outcome from the gateway.
 */
class PaymentController extends Controller
{
    public function __construct(
        private readonly PaymentService $payments,
        private readonly GatewayRegistry $gateways,
    ) {}

    /** Payment methods the customer can use right now. */
    public function methods(): JsonResponse
    {
        return response()->json(['data' => collect($this->gateways->available())->map(fn ($g) => [
            'id' => $g['driver']->driver(),
            'name' => $g['driver']->label(),
            'test_mode' => $g['gateway']->is_test_mode,
        ])->values()]);
    }

    public function store(Request $request): JsonResponse
    {
        $data = $request->validate([
            'plan' => ['required', 'string', 'exists:subscription_plans,slug'],
            'gateway' => ['required', 'string', 'max:50'],
            // Generated by the app per attempt; a retry of the same attempt reuses the same payment.
            'idempotency_key' => ['nullable', 'string', 'min:16', 'max:100'],
        ]);

        $plan = SubscriptionPlan::where('slug', $data['plan'])->first();

        try {
            $payment = $this->payments->start(
                $request->user(), $plan, $data['gateway'],
                $data['idempotency_key'] ?? (string) Str::uuid(),
            );
        } catch (PaymentException $e) {
            return response()->json(['error' => ['code' => $e->errorCode, 'message' => $e->getMessage()]], $e->status);
        }

        return response()->json([
            'payment' => $this->present($payment->load('plan')),
            'checkout_url' => $payment->status === 'pending' ? $payment->checkout_url : null,
        ], 201);
    }

    public function show(Request $request, string $uuid): JsonResponse
    {
        $payment = $this->owned($request, $uuid);

        // The webhook is the normal route to the result; this nudges providers that can be asked.
        if ($payment->status === 'pending' && $payment->updated_at->lt(now()->subSeconds(15))) {
            $this->payments->reconcile($payment);
            $payment->refresh();
        }

        return response()->json(['payment' => $this->present($payment->load('plan'))]);
    }

    public function index(Request $request): JsonResponse
    {
        $payments = Payment::with('plan')->where('user_id', $request->user()->id)
            ->latest('id')->limit(50)->get();

        return response()->json(['data' => $payments->map(fn ($p) => $this->present($p))->values()]);
    }

    private function owned(Request $request, string $uuid): Payment
    {
        return Payment::where('uuid', $uuid)->where('user_id', $request->user()->id)->firstOrFail();
    }

    /** @return array<string, mixed> */
    private function present(Payment $p): array
    {
        $driver = $this->gateways->driver($p->gateway);

        return [
            'id' => $p->uuid,
            'status' => $p->status,
            'plan' => $p->plan?->name_ar,
            'plan_slug' => $p->plan?->slug,
            'amount' => $p->amount_cents,
            'currency' => $p->currency,
            'gateway' => $driver?->label() ?? $p->gateway,
            'test_mode' => (bool) ($p->metadata['test_mode'] ?? false),
            'receipt_number' => $p->receipt_number,
            'failure_reason' => $p->status === 'failed' ? $p->failure_reason : null,
            'refunded_amount' => $p->refunded_amount_cents,
            'created_at' => $p->created_at->toIso8601String(),
            'paid_at' => $p->paid_at?->toIso8601String(),
            'period_ends_at' => $p->subscription?->current_period_ends_at?->toIso8601String(),
        ];
    }
}
